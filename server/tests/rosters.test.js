const request=require('supertest')
const app=require('../index')
const db=require('../db')
const {createTestLeague,createTestAdmin,createTestTeam,createTestPlayer,createTestMatch,generateToken,cleanupLeague}=require('./helpers')

describe('Team rosters, names and atomic goal attribution',()=>{
  const cleanup=[]
  let league,token,home,away,match
  const api=(method,url,id=league.id)=>request(app)[method](url).set('Authorization',`Bearer ${token}`).set('X-League-Id',String(id))
  const setLimit=limit=>api('put','/api/teams/roster-settings').send({max_roster_size:limit})
  beforeEach(async()=>{league=await createTestLeague();cleanup.push(league.id);const admin=await createTestAdmin(league.id);token=generateToken(admin.id,league.id);home=await createTestTeam(league.id);away=await createTestTeam(league.id);match=await createTestMatch(league.id,home.id,away.id,{status:'completed',homeScore:1,awayScore:0})})
  afterAll(async()=>{for(const id of cleanup)await cleanupLeague(id)})
  test('defaults to unlimited; presets and custom limits persist independently of scoring rules',async()=>{
    expect((await api('get','/api/teams/roster-settings')).body.data.max_roster_size).toBeNull()
    for(const limit of [10,15,20,7,null])expect((await setLimit(limit)).body.data.max_roster_size).toBe(limit)
    for(const max_roster_size of [0,-1,1.5,1001,'10',undefined])expect((await api('put','/api/teams/roster-settings').send({max_roster_size})).status).toBe(400)
    await setLimit(10)
    const rules=(await api('get','/api/rules')).body.data
    expect((await api('put','/api/rules').send({...rules,win_points:5})).status).toBe(200)
    expect((await api('get','/api/teams/roster-settings')).body.data.max_roster_size).toBe(10)
  })
  test('serializes concurrent additions at the exact roster capacity',async()=>{
    await setLimit(10)
    const responses=await Promise.all(Array.from({length:13},(_,i)=>api('post','/api/players').send({name:`Player ${i}`,team_id:home.id})))
    expect(responses.filter(response=>response.status===201)).toHaveLength(10)
    expect(responses.filter(response=>response.status===409)).toHaveLength(3)
    expect(responses.find(response=>response.status===409).body.error).toContain('roster limit (10/10)')
    expect((await api('get',`/api/players/team/${home.id}`)).body.data).toHaveLength(10)
    expect((await api('post','/api/players').send({name:'Separate roster',team_id:away.id})).status).toBe(201)
  })
  test('unlimited rosters accept more than the largest preset',async()=>{
    await setLimit(null)
    for(let i=0;i<22;i++)expect((await api('post','/api/players').send({name:`Unlimited ${i}`,team_id:home.id})).status).toBe(201)
    expect((await api('get','/api/teams')).body.data.find(team=>team.id===home.id).player_count).toBe(22)
  })
  test('lowering limits preserves existing players and blocks additions until capacity permits',async()=>{
    const players=[];for(let i=0;i<3;i++)players.push(await createTestPlayer(league.id,home.id))
    await setLimit(2)
    expect((await api('get',`/api/players/team/${home.id}`)).body.data).toHaveLength(3)
    expect((await api('post','/api/players').send({name:'Blocked',team_id:home.id})).status).toBe(409)
    expect((await api('delete',`/api/players/${players[0].id}`)).status).toBe(200)
    expect((await api('post','/api/players').send({name:'Still full',team_id:home.id})).status).toBe(409)
    await api('delete',`/api/players/${players[1].id}`)
    expect((await api('post','/api/players').send({name:'Capacity freed',team_id:home.id})).status).toBe(201)
  })
  test('player rename updates only the name, preserving player ID, goal IDs and totals',async()=>{
    const player=await createTestPlayer(league.id,home.id,'Original name')
    const {rows:[goal]}=await db.query('INSERT INTO goals(match_id,player_id,team_id)VALUES($1,$2,$3)RETURNING *',[match.id,player.id,home.id])
    const renamed=await api('put',`/api/players/${player.id}`).send({name:'  Corrected name  '})
    expect(renamed.status).toBe(200);expect(renamed.body.data).toMatchObject({id:player.id,name:'Corrected name',team_id:home.id})
    expect((await db.query('SELECT * FROM goals WHERE id=$1',[goal.id])).rows[0]).toEqual(goal)
    const scorer=(await request(app).get(`/api/players/${league.id}/top-scorers`)).body.data.find(row=>row.playerId===player.id)
    expect(scorer).toMatchObject({playerName:'Corrected name',goals:1})
    expect((await api('get',`/api/goals/match/${match.id}`)).body.data[0].player_name).toBe('Corrected name')
    expect((await api('delete',`/api/players/${player.id}`)).status).toBe(409)
    expect((await db.query('SELECT id FROM goals WHERE id=$1',[goal.id])).rowCount).toBe(1)
  })
  test('rename rejects invalid names and attempted transfers',async()=>{
    const player=await createTestPlayer(league.id,home.id)
    for(const name of ['', ' ', 'x'.repeat(101),{},null])expect((await api('put',`/api/players/${player.id}`).send({name})).status).toBe(400)
    expect((await api('put',`/api/players/${player.id}`).send({name:'Transfer',team_id:away.id})).status).toBe(400)
    expect((await api('post','/api/players').send({name:'   ',team_id:home.id})).status).toBe(400)
  })
  test('ownership and resource scoping protect all roster operations',async()=>{
    const foreign=await createTestLeague();cleanup.push(foreign.id);const foreignTeam=await createTestTeam(foreign.id);const foreignPlayer=await createTestPlayer(foreign.id,foreignTeam.id)
    expect((await api('get','/api/teams/roster-settings',foreign.id)).status).toBe(403)
    expect((await api('put','/api/teams/roster-settings',foreign.id).send({max_roster_size:1})).status).toBe(403)
    expect((await api('get',`/api/players/team/${foreignTeam.id}`)).status).toBe(404)
    expect((await api('put',`/api/players/${foreignPlayer.id}`).send({name:'Stolen'})).status).toBe(404)
    expect((await api('delete',`/api/players/${foreignPlayer.id}`)).status).toBe(404)
    expect((await api('post','/api/players').send({name:'Wrong league',team_id:foreignTeam.id})).status).toBe(403)
    expect((await request(app).put('/api/teams/roster-settings').send({max_roster_size:1})).status).toBe(401)
    const other=(await api('post','/api/leagues').send({name:'Other owned league'})).body.data;cleanup.push(other.id)
    await setLimit(1)
    expect((await api('get','/api/teams/roster-settings',other.id)).body.data.max_roster_size).toBeNull()
  })
  test('existing players can be attributed at capacity and new scorers roll back the whole result on failure',async()=>{
    const player=await createTestPlayer(league.id,home.id,'Existing scorer')
    const {rows:[goal]}=await db.query('INSERT INTO goals(match_id,player_id,team_id)VALUES($1,$2,$3)RETURNING *',[match.id,player.id,home.id])
    await setLimit(1)
    const denied=await api('put',`/api/fixtures/${match.id}/result`).send({home_score:2,away_score:0,scorers:[{team_id:home.id,new_name:'No room'}]})
    expect(denied.status).toBe(409)
    expect((await db.query('SELECT home_score FROM matches WHERE id=$1',[match.id])).rows[0].home_score).toBe(1)
    expect((await db.query('SELECT * FROM goals WHERE match_id=$1',[match.id])).rows).toEqual([goal])
    expect((await api('get',`/api/players/team/${home.id}`)).body.data).toHaveLength(1)
    const saved=await api('put',`/api/fixtures/${match.id}/result`).send({home_score:2,away_score:0,scorers:[{team_id:home.id,player_id:player.id},{team_id:home.id,player_id:player.id}]})
    expect(saved.status).toBe(200)
    expect((await api('get',`/api/goals/match/${match.id}`)).body.data).toHaveLength(2)
  })
  test('an atomic result exceeding remaining slots leaves no partial players, goals or scores',async()=>{
    await setLimit(1)
    const response=await api('put',`/api/fixtures/${match.id}/result`).send({home_score:2,away_score:0,scorers:[{team_id:home.id,new_name:'One'},{team_id:home.id,new_name:'Two'}]})
    expect(response.status).toBe(409)
    expect((await api('get',`/api/players/team/${home.id}`)).body.data).toHaveLength(0)
    expect((await api('get',`/api/goals/match/${match.id}`)).body.data).toHaveLength(0)
    expect((await db.query('SELECT home_score FROM matches WHERE id=$1',[match.id])).rows[0].home_score).toBe(1)
  })
  test('new scorer names reuse the same player within an atomic submission',async()=>{
    await setLimit(1)
    const response=await api('put',`/api/fixtures/${match.id}/result`).send({home_score:2,away_score:0,scorers:[{team_id:home.id,new_name:'Same scorer'},{team_id:home.id,new_name:'SAME SCORER'}]})
    expect(response.status).toBe(200)
    const players=(await api('get',`/api/players/team/${home.id}`)).body.data
    expect(players).toHaveLength(1)
    expect((await api('get',`/api/goals/match/${match.id}`)).body.data.map(goal=>goal.player_id)).toEqual([players[0].id,players[0].id])
  })
  test('atomic results reject foreign scorers and invalid goal counts without changing data',async()=>{
    const player=await createTestPlayer(league.id,away.id)
    for(const scorers of [[{team_id:home.id,player_id:player.id}],[{team_id:away.id,player_id:player.id}],[{team_id:home.id,new_name:'New'},{team_id:999999,new_name:'Foreign'}]]){
      const response=await api('put',`/api/fixtures/${match.id}/result`).send({home_score:1,away_score:0,scorers})
      expect([400,403]).toContain(response.status)
    }
    expect((await api('get',`/api/players/team/${home.id}`)).body.data).toHaveLength(0)
  })
  test('team deletion reports fixture constraints instead of silently removing history',async()=>{
    expect((await api('delete',`/api/teams/${home.id}`)).status).toBe(409)
    expect((await db.query('SELECT id FROM matches WHERE id=$1',[match.id])).rowCount).toBe(1)
  })
})
